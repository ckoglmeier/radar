-- Migration 090: Giving organization reviews and gift-request evaluations.
-- Why: research an organization against the approved giving rubric, then read one request
-- against that review, the person's causes and priorities, and the forward budget.
-- Completed artifacts are immutable; a refresh is a new row. Freshness = completed_at.
-- Nothing here references investment, pipeline or Council tables.

CREATE TABLE IF NOT EXISTS giving_org_reviews (
  seq BIGINT GENERATED BY DEFAULT AS IDENTITY,
  id TEXT PRIMARY KEY,
  workspace_id TEXT NOT NULL,
  organization_id TEXT NOT NULL REFERENCES giving_organizations(id) ON DELETE CASCADE,
  status TEXT NOT NULL CHECK (status IN ('running', 'completed', 'failed')),
  rubric_version INT NOT NULL CHECK (rubric_version > 0),
  inputs JSONB NOT NULL CHECK (jsonb_typeof(inputs) = 'object'),
  artifact JSONB CHECK (artifact IS NULL OR jsonb_typeof(artifact) = 'object'),
  retrieval JSONB,
  usage JSONB,
  error_code TEXT,
  error_message TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  completed_at TIMESTAMPTZ,
  CHECK ((status = 'completed') = (artifact IS NOT NULL AND completed_at IS NOT NULL))
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_giving_org_reviews_running
  ON giving_org_reviews(organization_id) WHERE status = 'running';
CREATE INDEX IF NOT EXISTS idx_giving_org_reviews_org ON giving_org_reviews(organization_id, seq DESC);

CREATE TABLE IF NOT EXISTS giving_request_evaluations (
  seq BIGINT GENERATED BY DEFAULT AS IDENTITY,
  id TEXT PRIMARY KEY,
  workspace_id TEXT NOT NULL,
  request_id TEXT NOT NULL REFERENCES giving_requests(id) ON DELETE CASCADE,
  org_review_id TEXT NOT NULL REFERENCES giving_org_reviews(id),
  status TEXT NOT NULL CHECK (status IN ('running', 'completed', 'failed')),
  inputs JSONB NOT NULL CHECK (jsonb_typeof(inputs) = 'object'),
  inputs_sha256 TEXT NOT NULL CHECK (inputs_sha256 ~ '^[0-9a-f]{64}$'),
  artifact JSONB CHECK (artifact IS NULL OR jsonb_typeof(artifact) = 'object'),
  usage JSONB,
  error_code TEXT,
  error_message TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  completed_at TIMESTAMPTZ,
  CHECK ((status = 'completed') = (artifact IS NOT NULL AND completed_at IS NOT NULL))
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_giving_request_evaluations_running
  ON giving_request_evaluations(request_id) WHERE status = 'running';
CREATE INDEX IF NOT EXISTS idx_giving_request_evaluations_request ON giving_request_evaluations(request_id, seq DESC);

-- A completed review or evaluation never changes. Restore sets the maintenance flag.
CREATE OR REPLACE FUNCTION radar_giving_completed_immutable() RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
  IF current_setting('radar.earned_equity_maintenance', true) = 'on' THEN
    RETURN NEW;
  END IF;
  IF OLD.status = 'completed' THEN
    RAISE EXCEPTION '% completed rows are immutable', TG_TABLE_NAME;
  END IF;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS radar_giving_org_reviews_immutable ON giving_org_reviews;
CREATE TRIGGER radar_giving_org_reviews_immutable
  BEFORE UPDATE ON giving_org_reviews FOR EACH ROW EXECUTE FUNCTION radar_giving_completed_immutable();
DROP TRIGGER IF EXISTS radar_giving_request_evaluations_immutable ON giving_request_evaluations;
CREATE TRIGGER radar_giving_request_evaluations_immutable
  BEFORE UPDATE ON giving_request_evaluations FOR EACH ROW EXECUTE FUNCTION radar_giving_completed_immutable();
