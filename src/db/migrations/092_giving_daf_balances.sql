-- DAF assets available for future grants. Neither balances nor plans are gifts,
-- personal investments, or additions to investment return calculations.
CREATE TABLE IF NOT EXISTS giving_daf_balances (
  seq BIGINT GENERATED BY DEFAULT AS IDENTITY,
  id TEXT PRIMARY KEY,
  workspace_id TEXT NOT NULL,
  account_ref TEXT NOT NULL,
  account_name TEXT NOT NULL,
  provider TEXT NOT NULL DEFAULT 'daffy' CHECK (provider = 'daffy'),
  currency TEXT NOT NULL DEFAULT 'USD' CHECK (currency = 'USD'),
  source TEXT NOT NULL CHECK (source IN ('daffy_api', 'manual')),
  as_of DATE NOT NULL,
  total_cents BIGINT NOT NULL CHECK (total_cents >= 0),
  available_cents BIGINT NOT NULL CHECK (available_cents >= 0 AND available_cents <= total_cents),
  invested_cents BIGINT CHECK (invested_cents IS NULL OR invested_cents >= 0),
  pending_cents BIGINT CHECK (pending_cents IS NULL OR pending_cents >= 0),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE (workspace_id, id)
);
CREATE INDEX IF NOT EXISTS idx_giving_daf_balances_latest ON giving_daf_balances(workspace_id, account_ref, as_of DESC, seq DESC);
CREATE TABLE IF NOT EXISTS giving_daf_plans (
  seq BIGINT GENERATED BY DEFAULT AS IDENTITY,
  id TEXT PRIMARY KEY,
  workspace_id TEXT NOT NULL,
  balance_id TEXT NOT NULL,
  assumptions JSONB NOT NULL CHECK (jsonb_typeof(assumptions) = 'object'),
  projection JSONB NOT NULL CHECK (jsonb_typeof(projection) = 'object'),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  FOREIGN KEY (workspace_id, balance_id) REFERENCES giving_daf_balances(workspace_id, id)
);
DROP TRIGGER IF EXISTS radar_giving_daf_balances_immutable ON giving_daf_balances;
CREATE TRIGGER radar_giving_daf_balances_immutable BEFORE UPDATE ON giving_daf_balances FOR EACH ROW EXECUTE FUNCTION radar_giving_append_only();
DROP TRIGGER IF EXISTS radar_giving_daf_plans_immutable ON giving_daf_plans;
CREATE TRIGGER radar_giving_daf_plans_immutable BEFORE UPDATE ON giving_daf_plans FOR EACH ROW EXECUTE FUNCTION radar_giving_append_only();
ALTER TABLE giving_transitions DROP CONSTRAINT IF EXISTS giving_transitions_subject_type_check;
ALTER TABLE giving_transitions ADD CONSTRAINT giving_transitions_subject_type_check CHECK (subject_type IN ('request', 'pledge', 'gift', 'refund', 'daf_contribution', 'source', 'source_item', 'organization', 'lens', 'budget', 'snapshot', 'settings', 'daf_balance', 'daf_plan'));
