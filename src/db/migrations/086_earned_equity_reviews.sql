-- Migration 086: Earned Equity company and offer reviews.
-- Why: the lens reviews a company once (reusable across offers) and writes a separate personal offer memo.
-- These tables never join pipeline_invites, council_runs, deal_evaluations, ad_hoc_reviews or council_followups,
-- so angel calibration and Pipeline counts cannot see them. Completed artifacts are immutable.

CREATE TABLE IF NOT EXISTS earned_equity_company_reviews (
  seq BIGINT GENERATED BY DEFAULT AS IDENTITY,
  id TEXT PRIMARY KEY,
  portfolio_entity_id UUID NOT NULL REFERENCES portfolio_entities(id),
  parent_review_id TEXT REFERENCES earned_equity_company_reviews(id),
  review_kind TEXT NOT NULL CHECK (review_kind IN ('initial', 'refresh', 'followup')),
  lens_id TEXT NOT NULL,
  lens_version TEXT NOT NULL,
  policy_version TEXT NOT NULL,
  instruction_hash TEXT NOT NULL CHECK (instruction_hash ~ '^[0-9a-f]{64}$'),
  source_manifest_hash TEXT NOT NULL CHECK (source_manifest_hash ~ '^[0-9a-f]{64}$'),
  run_key TEXT NOT NULL UNIQUE CHECK (run_key ~ '^[0-9a-f]{64}$'),
  status TEXT NOT NULL CHECK (status IN ('running', 'completed', 'failed')),
  stage TEXT,
  artifact JSONB,
  error_code TEXT,
  usage JSONB,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  completed_at TIMESTAMPTZ,
  CHECK ((review_kind = 'followup') = (parent_review_id IS NOT NULL)),
  CHECK ((status = 'completed') = (artifact IS NOT NULL AND completed_at IS NOT NULL))
);
-- One running review per company.
CREATE UNIQUE INDEX IF NOT EXISTS uq_earned_equity_company_reviews_running
  ON earned_equity_company_reviews(portfolio_entity_id) WHERE status = 'running';
CREATE INDEX IF NOT EXISTS idx_earned_equity_company_reviews_entity
  ON earned_equity_company_reviews(portfolio_entity_id, seq);

CREATE TABLE IF NOT EXISTS earned_equity_offer_reviews (
  seq BIGINT GENERATED BY DEFAULT AS IDENTITY,
  id TEXT PRIMARY KEY,
  offer_revision_id TEXT NOT NULL REFERENCES earned_equity_offer_revisions(id) ON DELETE CASCADE,
  company_review_id TEXT REFERENCES earned_equity_company_reviews(id),
  snapshot_id TEXT REFERENCES earned_equity_analysis_snapshots(id) ON DELETE CASCADE,
  parent_review_id TEXT REFERENCES earned_equity_offer_reviews(id) ON DELETE CASCADE,
  review_kind TEXT NOT NULL CHECK (review_kind IN ('initial', 'followup')),
  run_key TEXT NOT NULL UNIQUE CHECK (run_key ~ '^[0-9a-f]{64}$'),
  status TEXT NOT NULL CHECK (status IN ('running', 'completed', 'failed')),
  artifact JSONB,
  error_code TEXT,
  usage JSONB,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  completed_at TIMESTAMPTZ,
  CHECK ((review_kind = 'followup') = (parent_review_id IS NOT NULL)),
  CHECK ((status = 'completed') = (artifact IS NOT NULL AND completed_at IS NOT NULL))
);
CREATE INDEX IF NOT EXISTS idx_earned_equity_offer_reviews_revision
  ON earned_equity_offer_reviews(offer_revision_id, seq);
CREATE INDEX IF NOT EXISTS idx_earned_equity_offer_reviews_company_review
  ON earned_equity_offer_reviews(company_review_id);

-- A running or failed review may progress. A completed review, and the identity of any review, never changes.
-- Deliberate purge and restore set the same transaction-local flag migration 084 uses.
CREATE OR REPLACE FUNCTION radar_earned_equity_review_guard() RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
  IF current_setting('radar.earned_equity_maintenance', true) = 'on' THEN
    IF TG_OP = 'DELETE' THEN RETURN OLD; END IF;
    RETURN NEW;
  END IF;
  IF OLD.status = 'completed' THEN
    RAISE EXCEPTION '% completed reviews are immutable', TG_TABLE_NAME;
  END IF;
  IF TG_OP = 'DELETE' THEN RETURN OLD; END IF;
  IF NEW.id IS DISTINCT FROM OLD.id
     OR NEW.run_key IS DISTINCT FROM OLD.run_key
     OR NEW.review_kind IS DISTINCT FROM OLD.review_kind
     OR NEW.parent_review_id IS DISTINCT FROM OLD.parent_review_id
     OR NEW.created_at IS DISTINCT FROM OLD.created_at THEN
    RAISE EXCEPTION '% review identity is immutable', TG_TABLE_NAME;
  END IF;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS radar_earned_equity_company_reviews_guard ON earned_equity_company_reviews;
CREATE TRIGGER radar_earned_equity_company_reviews_guard
  BEFORE UPDATE OR DELETE ON earned_equity_company_reviews
  FOR EACH ROW EXECUTE FUNCTION radar_earned_equity_review_guard();

DROP TRIGGER IF EXISTS radar_earned_equity_offer_reviews_guard ON earned_equity_offer_reviews;
CREATE TRIGGER radar_earned_equity_offer_reviews_guard
  BEFORE UPDATE OR DELETE ON earned_equity_offer_reviews
  FOR EACH ROW EXECUTE FUNCTION radar_earned_equity_review_guard();
