-- Migration 087: links from a confirmed Earned Equity offer component to the ledger grant it produced.
-- Why: an accepted offer becomes a holding only through an explicit, user-confirmed action.
-- The link is the idempotency anchor (one grant per offer component) and keeps the full
-- confirmation, including the vesting schedule, as the user stated it. It is append-only;
-- purging the offer tree deletes links under the maintenance flag and never touches the ledger.

CREATE TABLE IF NOT EXISTS earned_equity_grant_links (
  seq BIGINT GENERATED BY DEFAULT AS IDENTITY,
  id TEXT PRIMARY KEY,
  decision_id TEXT NOT NULL REFERENCES earned_equity_decisions(id),
  offer_revision_id TEXT NOT NULL REFERENCES earned_equity_offer_revisions(id),
  grant_component_id TEXT NOT NULL,
  investment_id INT NOT NULL REFERENCES investments(id),
  grant_id UUID NOT NULL REFERENCES employment_equity_grants(id),
  confirmed_terms JSONB NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE (offer_revision_id, grant_component_id),
  UNIQUE (grant_id)
);
CREATE INDEX IF NOT EXISTS idx_earned_equity_grant_links_investment
  ON earned_equity_grant_links(investment_id);
CREATE INDEX IF NOT EXISTS idx_earned_equity_grant_links_decision
  ON earned_equity_grant_links(decision_id);

DROP TRIGGER IF EXISTS radar_earned_equity_grant_links_append_only ON earned_equity_grant_links;
CREATE TRIGGER radar_earned_equity_grant_links_append_only
  BEFORE UPDATE OR DELETE ON earned_equity_grant_links
  FOR EACH ROW EXECUTE FUNCTION radar_earned_equity_append_only();
