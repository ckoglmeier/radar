-- Migration 085: Earned Equity offer-document reviews.
-- Why: uploaded offer documents are classified and extracted into PROPOSALS that the user
-- confirms before an offer revision is saved. Extraction never creates grants or revisions.
-- Documents attach to an opportunity (entity_type 'earned_equity_opportunity'); personal terms
-- never join company-wide tables.
--
-- Status model (chosen design): proposal content is immutable. The only permitted change to an
-- existing row is the guarded status transition
--   proposed -> confirmed (requires confirmed_offer_revision_id) | proposed -> rejected,
-- enforced by trigger. A re-run of extraction inserts a NEW row (higher seq); old rows are never
-- rewritten. 'failed' is an insert-time status (OCR/parse failure) and is terminal.

ALTER TABLE documents
  DROP CONSTRAINT IF EXISTS documents_entity_type_check;

ALTER TABLE documents
  ADD CONSTRAINT documents_entity_type_check CHECK (
    entity_type IN (
      'investment',
      'pipeline_invite',
      'company_update',
      'deal_evaluation',
      'portfolio_entity',
      'room_holding',
      'file_vault_entry',
      'earned_equity_opportunity'
    )
  );

CREATE TABLE IF NOT EXISTS earned_equity_document_reviews (
  seq BIGINT GENERATED BY DEFAULT AS IDENTITY,
  id TEXT PRIMARY KEY,
  opportunity_id TEXT NOT NULL REFERENCES earned_equity_opportunities(id),
  document_id INT NOT NULL REFERENCES documents(id),
  document_sha256 TEXT NOT NULL CHECK (document_sha256 ~ '^[0-9a-f]{64}$'),
  doc_class TEXT NOT NULL CHECK (doc_class IN (
    'cover_letter', 'offer_letter', 'grant_notice', 'equity_plan', 'service_agreement',
    'ciia', 'amendment', 'cap_disclosure', 'education', 'benefits_overview', 'other'
  )),
  extraction_version TEXT NOT NULL,
  status TEXT NOT NULL CHECK (status IN ('proposed', 'confirmed', 'rejected', 'failed')),
  proposal JSONB NOT NULL,
  confirmed_offer_revision_id TEXT REFERENCES earned_equity_offer_revisions(id),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  status_changed_at TIMESTAMPTZ,
  CHECK ((status = 'confirmed') = (confirmed_offer_revision_id IS NOT NULL))
);
CREATE INDEX IF NOT EXISTS idx_earned_equity_document_reviews_opportunity
  ON earned_equity_document_reviews(opportunity_id, seq);
CREATE INDEX IF NOT EXISTS idx_earned_equity_document_reviews_document
  ON earned_equity_document_reviews(document_id, seq);

CREATE OR REPLACE FUNCTION radar_earned_equity_document_reviews_guard() RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
  -- Restore and deliberate purge set this transaction-local flag; nothing else may rewrite history.
  IF current_setting('radar.earned_equity_maintenance', true) = 'on' THEN
    IF TG_OP = 'DELETE' THEN RETURN OLD; END IF;
    RETURN NEW;
  END IF;
  IF TG_OP = 'DELETE' THEN
    RAISE EXCEPTION '% rows can only be removed by an opportunity purge', TG_TABLE_NAME;
  END IF;
  IF NEW.seq IS DISTINCT FROM OLD.seq OR NEW.id IS DISTINCT FROM OLD.id
     OR NEW.opportunity_id IS DISTINCT FROM OLD.opportunity_id
     OR NEW.document_id IS DISTINCT FROM OLD.document_id
     OR NEW.document_sha256 IS DISTINCT FROM OLD.document_sha256
     OR NEW.doc_class IS DISTINCT FROM OLD.doc_class
     OR NEW.extraction_version IS DISTINCT FROM OLD.extraction_version
     OR NEW.proposal IS DISTINCT FROM OLD.proposal
     OR NEW.created_at IS DISTINCT FROM OLD.created_at THEN
    RAISE EXCEPTION '% proposal content is append-only', TG_TABLE_NAME;
  END IF;
  IF OLD.status <> 'proposed' OR NEW.status NOT IN ('confirmed', 'rejected') THEN
    RAISE EXCEPTION '% status cannot change from % to %', TG_TABLE_NAME, OLD.status, NEW.status;
  END IF;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS radar_earned_equity_document_reviews_guard ON earned_equity_document_reviews;
CREATE TRIGGER radar_earned_equity_document_reviews_guard
  BEFORE UPDATE OR DELETE ON earned_equity_document_reviews
  FOR EACH ROW EXECUTE FUNCTION radar_earned_equity_document_reviews_guard();
