-- Migration 089: Giving (philanthropy) records, intake provenance, lens, budgets and snapshots.
-- Why: track confirmed household giving and incoming gift requests without touching
-- investment records. No table here references portfolio_entities, pipeline_invites,
-- council_runs or evaluations, so gifts can never enter MOIC, IRR, Pipeline or calibration.
-- Owner scope follows the host-assisted tables: workspace_id ('local' on Desktop).
-- Research artifacts (org reviews, request evaluations) arrive in a later migration.

CREATE TABLE IF NOT EXISTS giving_household_members (
  id TEXT PRIMARY KEY,
  workspace_id TEXT NOT NULL,
  display_name TEXT NOT NULL CHECK (length(display_name) BETWEEN 1 AND 80),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE (workspace_id, display_name)
);

-- One identity per organization. EIN is the strong key when known; names never merge on their own.
CREATE TABLE IF NOT EXISTS giving_organizations (
  id TEXT PRIMARY KEY,
  workspace_id TEXT NOT NULL,
  name TEXT NOT NULL CHECK (length(name) BETWEEN 1 AND 300),
  ein TEXT CHECK (ein IS NULL OR ein ~ '^[0-9]{9}$'),
  aliases JSONB NOT NULL DEFAULT '[]'::jsonb CHECK (jsonb_typeof(aliases) = 'array'),
  website TEXT,
  registry_snapshot JSONB CHECK (registry_snapshot IS NULL OR jsonb_typeof(registry_snapshot) = 'object'),
  registry_checked_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_giving_organizations_ein
  ON giving_organizations(workspace_id, ein) WHERE ein IS NOT NULL;

-- One intake batch (a Gmail scan file, an upload, a manual entry or a labeled sample batch).
CREATE TABLE IF NOT EXISTS giving_sources (
  seq BIGINT GENERATED BY DEFAULT AS IDENTITY,
  id TEXT PRIMARY KEY,
  workspace_id TEXT NOT NULL,
  member_id TEXT REFERENCES giving_household_members(id) ON DELETE SET NULL,
  kind TEXT NOT NULL CHECK (kind IN ('gmail_scan', 'upload', 'manual', 'sample')),
  label TEXT NOT NULL CHECK (length(label) BETWEEN 1 AND 300),
  file_name TEXT,
  file_sha256 TEXT CHECK (file_sha256 IS NULL OR file_sha256 ~ '^[0-9a-f]{64}$'),
  metadata JSONB NOT NULL DEFAULT '{}'::jsonb CHECK (jsonb_typeof(metadata) = 'object'),
  imported_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  removed_at TIMESTAMPTZ
);
CREATE INDEX IF NOT EXISTS idx_giving_sources_workspace ON giving_sources(workspace_id, seq);

CREATE TABLE IF NOT EXISTS giving_requests (
  id TEXT PRIMARY KEY,
  workspace_id TEXT NOT NULL,
  organization_id TEXT NOT NULL REFERENCES giving_organizations(id),
  member_id TEXT REFERENCES giving_household_members(id) ON DELETE SET NULL,
  purpose TEXT,
  requested_cents BIGINT CHECK (requested_cents IS NULL OR requested_cents > 0),
  currency TEXT NOT NULL DEFAULT 'USD' CHECK (currency ~ '^[A-Z]{3}$'),
  deadline DATE,
  status TEXT NOT NULL DEFAULT 'requested'
    CHECK (status IN ('requested', 'evaluating', 'approved', 'pledged', 'deferred', 'passed', 'cancelled')),
  decided_cents BIGINT CHECK (decided_cents IS NULL OR decided_cents >= 0),
  rationale TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_giving_requests_workspace ON giving_requests(workspace_id, status, updated_at DESC);

CREATE TABLE IF NOT EXISTS giving_pledges (
  id TEXT PRIMARY KEY,
  workspace_id TEXT NOT NULL,
  organization_id TEXT NOT NULL REFERENCES giving_organizations(id),
  member_id TEXT REFERENCES giving_household_members(id) ON DELETE SET NULL,
  request_id TEXT UNIQUE REFERENCES giving_requests(id),
  purpose TEXT,
  restriction TEXT,
  total_cents BIGINT NOT NULL CHECK (total_cents > 0),
  currency TEXT NOT NULL DEFAULT 'USD' CHECK (currency ~ '^[A-Z]{3}$'),
  pledged_on DATE,
  schedule_text TEXT,
  status TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'cancelled')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Paid money only. Planned or pledged amounts never live here. A request is "paid"
-- only through a confirmed gift that references it.
CREATE TABLE IF NOT EXISTS giving_gifts (
  id TEXT PRIMARY KEY,
  workspace_id TEXT NOT NULL,
  organization_id TEXT NOT NULL REFERENCES giving_organizations(id),
  member_id TEXT REFERENCES giving_household_members(id) ON DELETE SET NULL,
  purpose TEXT,
  restriction TEXT,
  amount_cents BIGINT NOT NULL CHECK (amount_cents > 0),
  currency TEXT NOT NULL DEFAULT 'USD' CHECK (currency ~ '^[A-Z]{3}$'),
  paid_on DATE,
  vehicle TEXT NOT NULL CHECK (vehicle IN ('direct', 'daf_grant', 'employer_match', 'unknown')),
  daf_provider TEXT,
  pledge_id TEXT REFERENCES giving_pledges(id),
  request_id TEXT REFERENCES giving_requests(id),
  voided_at TIMESTAMPTZ,
  void_reason TEXT,
  confirmed_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CHECK ((voided_at IS NULL) = (void_reason IS NULL))
);
CREATE INDEX IF NOT EXISTS idx_giving_gifts_workspace ON giving_gifts(workspace_id, paid_on);
CREATE INDEX IF NOT EXISTS idx_giving_gifts_org ON giving_gifts(organization_id);

CREATE TABLE IF NOT EXISTS giving_refunds (
  id TEXT PRIMARY KEY,
  workspace_id TEXT NOT NULL,
  gift_id TEXT NOT NULL REFERENCES giving_gifts(id) ON DELETE CASCADE,
  amount_cents BIGINT NOT NULL CHECK (amount_cents > 0),
  refunded_on DATE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_giving_refunds_gift ON giving_refunds(gift_id);

-- Money moved into a donor-advised fund. Never counted as recipient giving.
CREATE TABLE IF NOT EXISTS giving_daf_contributions (
  id TEXT PRIMARY KEY,
  workspace_id TEXT NOT NULL,
  member_id TEXT REFERENCES giving_household_members(id) ON DELETE SET NULL,
  provider TEXT NOT NULL CHECK (length(provider) BETWEEN 1 AND 80),
  amount_cents BIGINT NOT NULL CHECK (amount_cents > 0),
  currency TEXT NOT NULL DEFAULT 'USD' CHECK (currency ~ '^[A-Z]{3}$'),
  contributed_on DATE,
  voided_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Proposed records from a source. Confirmation links the item to exactly the record it evidences.
-- Several items may evidence one gift (an email receipt plus a Daffy grant line).
CREATE TABLE IF NOT EXISTS giving_source_items (
  seq BIGINT GENERATED BY DEFAULT AS IDENTITY,
  id TEXT PRIMARY KEY,
  workspace_id TEXT NOT NULL,
  source_id TEXT NOT NULL REFERENCES giving_sources(id) ON DELETE CASCADE,
  external_key TEXT NOT NULL CHECK (length(external_key) BETWEEN 1 AND 300),
  kind TEXT NOT NULL CHECK (kind IN ('receipt', 'daf_grant', 'daf_contribution', 'solicitation', 'pledge',
    'pledge_payment', 'refund', 'recurring_notice', 'not_a_gift', 'unknown')),
  excerpt TEXT NOT NULL,
  proposed JSONB NOT NULL CHECK (jsonb_typeof(proposed) = 'object'),
  issues JSONB NOT NULL DEFAULT '[]'::jsonb CHECK (jsonb_typeof(issues) = 'array'),
  status TEXT NOT NULL DEFAULT 'proposed'
    CHECK (status IN ('proposed', 'confirmed', 'rejected', 'duplicate', 'withdrawn')),
  organization_id TEXT REFERENCES giving_organizations(id),
  gift_id TEXT REFERENCES giving_gifts(id) ON DELETE SET NULL,
  refund_id TEXT REFERENCES giving_refunds(id) ON DELETE SET NULL,
  pledge_id TEXT REFERENCES giving_pledges(id) ON DELETE SET NULL,
  request_id TEXT REFERENCES giving_requests(id) ON DELETE SET NULL,
  daf_contribution_id TEXT REFERENCES giving_daf_contributions(id) ON DELETE SET NULL,
  decided_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE (workspace_id, external_key)
);
CREATE INDEX IF NOT EXISTS idx_giving_source_items_source ON giving_source_items(source_id, seq);
CREATE INDEX IF NOT EXISTS idx_giving_source_items_status ON giving_source_items(workspace_id, status);
CREATE INDEX IF NOT EXISTS idx_giving_source_items_gift ON giving_source_items(gift_id);

-- Every material change, with what was confirmed. Append-only.
CREATE TABLE IF NOT EXISTS giving_transitions (
  seq BIGINT GENERATED BY DEFAULT AS IDENTITY,
  id TEXT PRIMARY KEY,
  workspace_id TEXT NOT NULL,
  subject_type TEXT NOT NULL CHECK (subject_type IN ('request', 'pledge', 'gift', 'refund', 'daf_contribution',
    'source', 'source_item', 'organization', 'lens', 'budget', 'snapshot')),
  subject_id TEXT NOT NULL,
  action TEXT NOT NULL CHECK (length(action) BETWEEN 1 AND 80),
  from_status TEXT,
  to_status TEXT,
  detail JSONB NOT NULL DEFAULT '{}'::jsonb CHECK (jsonb_typeof(detail) = 'object'),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_giving_transitions_workspace ON giving_transitions(workspace_id, seq DESC);
CREATE INDEX IF NOT EXISTS idx_giving_transitions_subject ON giving_transitions(subject_type, subject_id, seq);

-- Causes (unranked) and priorities (ordered, at most six). Append-only versions; newest is current.
-- Empty lists are an intentional "unspecified" and are never repopulated.
CREATE TABLE IF NOT EXISTS giving_lens_versions (
  seq BIGINT GENERATED BY DEFAULT AS IDENTITY,
  id TEXT PRIMARY KEY,
  workspace_id TEXT NOT NULL,
  version INT NOT NULL CHECK (version > 0),
  lens JSONB NOT NULL CHECK (jsonb_typeof(lens) = 'object'),
  lens_sha256 TEXT NOT NULL CHECK (lens_sha256 ~ '^[0-9a-f]{64}$'),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE (workspace_id, version)
);

-- Forward budget versions with fixed dates. Skipped means no dollar plan; zero is a real budget.
CREATE TABLE IF NOT EXISTS giving_budgets (
  seq BIGINT GENERATED BY DEFAULT AS IDENTITY,
  id TEXT PRIMARY KEY,
  workspace_id TEXT NOT NULL,
  version INT NOT NULL CHECK (version > 0),
  starts_on DATE NOT NULL,
  ends_on DATE NOT NULL,
  mode TEXT NOT NULL CHECK (mode IN ('recorded', 'custom', 'skipped')),
  amount_cents BIGINT CHECK (amount_cents IS NULL OR amount_cents >= 0),
  currency TEXT NOT NULL DEFAULT 'USD' CHECK (currency ~ '^[A-Z]{3}$'),
  planned JSONB NOT NULL DEFAULT '[]'::jsonb CHECK (jsonb_typeof(planned) = 'array'),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CHECK (ends_on > starts_on),
  CHECK ((mode = 'skipped') = (amount_cents IS NULL)),
  UNIQUE (workspace_id, version)
);

-- Dated report and decision snapshots. Never rewritten.
CREATE TABLE IF NOT EXISTS giving_snapshots (
  seq BIGINT GENERATED BY DEFAULT AS IDENTITY,
  id TEXT PRIMARY KEY,
  workspace_id TEXT NOT NULL,
  kind TEXT NOT NULL CHECK (kind IN ('report', 'decision')),
  as_of DATE NOT NULL,
  subject_id TEXT,
  label TEXT,
  payload JSONB NOT NULL CHECK (jsonb_typeof(payload) = 'object'),
  payload_sha256 TEXT NOT NULL CHECK (payload_sha256 ~ '^[0-9a-f]{64}$'),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_giving_snapshots_workspace ON giving_snapshots(workspace_id, kind, seq DESC);

-- Append-only and immutable tables. Deletion (reset) is allowed; edits are not.
-- Restore sets the same transaction-local flag migration 084 uses.
CREATE OR REPLACE FUNCTION radar_giving_append_only() RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
  IF current_setting('radar.earned_equity_maintenance', true) = 'on' THEN
    RETURN NEW;
  END IF;
  RAISE EXCEPTION '% rows are immutable', TG_TABLE_NAME;
END;
$$;

DROP TRIGGER IF EXISTS radar_giving_transitions_immutable ON giving_transitions;
CREATE TRIGGER radar_giving_transitions_immutable
  BEFORE UPDATE ON giving_transitions FOR EACH ROW EXECUTE FUNCTION radar_giving_append_only();
DROP TRIGGER IF EXISTS radar_giving_lens_versions_immutable ON giving_lens_versions;
CREATE TRIGGER radar_giving_lens_versions_immutable
  BEFORE UPDATE ON giving_lens_versions FOR EACH ROW EXECUTE FUNCTION radar_giving_append_only();
DROP TRIGGER IF EXISTS radar_giving_budgets_immutable ON giving_budgets;
CREATE TRIGGER radar_giving_budgets_immutable
  BEFORE UPDATE ON giving_budgets FOR EACH ROW EXECUTE FUNCTION radar_giving_append_only();
DROP TRIGGER IF EXISTS radar_giving_snapshots_immutable ON giving_snapshots;
CREATE TRIGGER radar_giving_snapshots_immutable
  BEFORE UPDATE ON giving_snapshots FOR EACH ROW EXECUTE FUNCTION radar_giving_append_only();
