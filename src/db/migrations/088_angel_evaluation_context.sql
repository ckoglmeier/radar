-- Migration 088: one-time angel evaluation drafts, reusable business preferences,
-- immutable evaluation context snapshots and personal-fit synthesis jobs.
-- Why: evaluate one deal with personal context in two dimensions (what to back,
-- how the business should work) without touching objective Council inputs.
-- Additive only. Existing evaluations have no context row and render as before.
-- Owner scope follows the host-assisted tables: workspace_id ('local' on Desktop).

-- Reusable HOW list. Append-only versions; the newest version is current.
-- An empty items array is a saved, intentional "unspecified" and is never
-- repopulated with suggestions. WHAT reuses existing theses (no new store).
CREATE TABLE IF NOT EXISTS angel_business_preference_lists (
  seq BIGINT GENERATED BY DEFAULT AS IDENTITY,
  id TEXT PRIMARY KEY,
  workspace_id TEXT NOT NULL,
  domain TEXT NOT NULL DEFAULT 'angel' CHECK (domain = 'angel'),
  version INT NOT NULL CHECK (version > 0),
  items JSONB NOT NULL CHECK (jsonb_typeof(items) = 'array' AND jsonb_array_length(items) <= 6),
  confirmed_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE (workspace_id, domain, version)
);

-- Private draft between steps. Saving never runs research.
CREATE TABLE IF NOT EXISTS angel_evaluation_drafts (
  id TEXT PRIMARY KEY,
  workspace_id TEXT NOT NULL,
  pipeline_invite_id INT REFERENCES pipeline_invites(id) ON DELETE SET NULL,
  revision INT NOT NULL DEFAULT 1 CHECK (revision > 0),
  state JSONB NOT NULL CHECK (jsonb_typeof(state) = 'object'),
  status TEXT NOT NULL DEFAULT 'draft' CHECK (status IN ('draft', 'submitted', 'discarded')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_angel_evaluation_drafts_workspace
  ON angel_evaluation_drafts(workspace_id, status, updated_at DESC);

-- Immutable evaluation context, captured at submission. One per confirmed
-- draft revision (the submission idempotency anchor). council_run_id is set
-- exactly once after the run is queued.
CREATE TABLE IF NOT EXISTS angel_evaluation_contexts (
  seq BIGINT GENERATED BY DEFAULT AS IDENTITY,
  id TEXT PRIMARY KEY,
  workspace_id TEXT NOT NULL,
  draft_id TEXT NOT NULL,
  draft_revision INT NOT NULL,
  pipeline_invite_id INT NOT NULL REFERENCES pipeline_invites(id) ON DELETE CASCADE,
  council_run_id INT UNIQUE REFERENCES council_runs(id) ON DELETE CASCADE,
  contract_version INT NOT NULL CHECK (contract_version > 0),
  snapshot JSONB NOT NULL CHECK (jsonb_typeof(snapshot) = 'object'),
  snapshot_sha256 TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE (workspace_id, draft_id, draft_revision)
);
CREATE INDEX IF NOT EXISTS idx_angel_evaluation_contexts_invite
  ON angel_evaluation_contexts(pipeline_invite_id, created_at DESC);

CREATE OR REPLACE FUNCTION radar_angel_context_immutable() RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
  IF current_setting('radar.earned_equity_maintenance', true) = 'on' THEN
    RETURN NEW;
  END IF;
  IF NEW.snapshot IS DISTINCT FROM OLD.snapshot
     OR NEW.snapshot_sha256 IS DISTINCT FROM OLD.snapshot_sha256
     OR NEW.workspace_id IS DISTINCT FROM OLD.workspace_id
     OR NEW.draft_id IS DISTINCT FROM OLD.draft_id
     OR NEW.draft_revision IS DISTINCT FROM OLD.draft_revision
     OR NEW.pipeline_invite_id IS DISTINCT FROM OLD.pipeline_invite_id
     OR NEW.contract_version IS DISTINCT FROM OLD.contract_version
     OR (OLD.council_run_id IS NOT NULL AND NEW.council_run_id IS DISTINCT FROM OLD.council_run_id) THEN
    RAISE EXCEPTION 'angel_evaluation_contexts snapshots are immutable';
  END IF;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS radar_angel_evaluation_contexts_immutable ON angel_evaluation_contexts;
CREATE TRIGGER radar_angel_evaluation_contexts_immutable
  BEFORE UPDATE ON angel_evaluation_contexts
  FOR EACH ROW EXECUTE FUNCTION radar_angel_context_immutable();

-- Personal-fit synthesis job, one per context. It waits until the objective
-- run completes, then runs from the stored objective output. A failure never
-- touches the objective report; retry re-queues only this job.
-- not_applicable: both dimensions intentionally unspecified (general assessment).
CREATE TABLE IF NOT EXISTS angel_personal_fit_jobs (
  id SERIAL PRIMARY KEY,
  context_id TEXT NOT NULL UNIQUE REFERENCES angel_evaluation_contexts(id) ON DELETE CASCADE,
  workspace_id TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'waiting'
    CHECK (status IN ('waiting', 'running', 'completed', 'failed', 'not_applicable')),
  attempt_number INT NOT NULL DEFAULT 0,
  claim_token TEXT,
  claim_expires_at TIMESTAMPTZ,
  input_sha256 TEXT,
  result JSONB CHECK (result IS NULL OR jsonb_typeof(result) = 'object'),
  usage_snapshot JSONB,
  error_code TEXT,
  error_message TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  completed_at TIMESTAMPTZ
);
CREATE INDEX IF NOT EXISTS idx_angel_personal_fit_jobs_status
  ON angel_personal_fit_jobs(status, updated_at);

CREATE OR REPLACE FUNCTION radar_angel_personal_fit_result_immutable() RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
  IF current_setting('radar.earned_equity_maintenance', true) = 'on' THEN
    RETURN NEW;
  END IF;
  IF OLD.status = 'completed' THEN
    RAISE EXCEPTION 'Completed personal-fit results are immutable';
  END IF;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS radar_angel_personal_fit_jobs_immutable ON angel_personal_fit_jobs;
CREATE TRIGGER radar_angel_personal_fit_jobs_immutable
  BEFORE UPDATE ON angel_personal_fit_jobs
  FOR EACH ROW EXECUTE FUNCTION radar_angel_personal_fit_result_immutable();
