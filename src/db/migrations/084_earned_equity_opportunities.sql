-- Migration 084: Earned Equity opportunity, offer-revision, snapshot and decision records.
-- Why: prospective employment/advisory/board offers are compared before any grant exists.
-- These tables never join investments or the grant ledger; personal terms stay out of company tables.

CREATE TABLE IF NOT EXISTS earned_equity_decision_groups (
  id TEXT PRIMARY KEY,
  mode TEXT NOT NULL CHECK (mode IN ('employment', 'advisory')),
  status TEXT NOT NULL CHECK (status IN ('open', 'decided', 'archived')),
  revision INTEGER NOT NULL CHECK (revision >= 1),
  payload JSONB NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS earned_equity_opportunities (
  id TEXT PRIMARY KEY,
  group_id TEXT NOT NULL REFERENCES earned_equity_decision_groups(id),
  portfolio_entity_id UUID REFERENCES portfolio_entities(id),
  relationship TEXT NOT NULL CHECK (relationship IN ('employment', 'advisory', 'board', 'other')),
  lifecycle TEXT NOT NULL CHECK (lifecycle IN ('considering', 'offer_received', 'accepted', 'declined', 'expired', 'withdrawn')),
  revision INTEGER NOT NULL DEFAULT 1 CHECK (revision >= 1),
  payload JSONB NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_earned_equity_opportunities_group
  ON earned_equity_opportunities(group_id);

CREATE TABLE IF NOT EXISTS earned_equity_offer_revisions (
  seq BIGINT GENERATED BY DEFAULT AS IDENTITY,
  id TEXT PRIMARY KEY,
  opportunity_id TEXT NOT NULL REFERENCES earned_equity_opportunities(id),
  supersedes_revision_id TEXT REFERENCES earned_equity_offer_revisions(id),
  as_of_date DATE NOT NULL,
  status TEXT NOT NULL CHECK (status IN ('proposed', 'signed', 'user_reported')),
  payload JSONB NOT NULL,
  payload_sha256 TEXT NOT NULL CHECK (payload_sha256 ~ '^[0-9a-f]{64}$'),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
-- One successor per revision, and one root per opportunity: history cannot fork.
CREATE UNIQUE INDEX IF NOT EXISTS uq_earned_equity_offer_revisions_supersedes
  ON earned_equity_offer_revisions(supersedes_revision_id)
  WHERE supersedes_revision_id IS NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS uq_earned_equity_offer_revisions_root
  ON earned_equity_offer_revisions(opportunity_id)
  WHERE supersedes_revision_id IS NULL;
CREATE INDEX IF NOT EXISTS idx_earned_equity_offer_revisions_opportunity
  ON earned_equity_offer_revisions(opportunity_id);

CREATE TABLE IF NOT EXISTS earned_equity_analysis_snapshots (
  seq BIGINT GENERATED BY DEFAULT AS IDENTITY,
  id TEXT PRIMARY KEY,
  offer_revision_id TEXT NOT NULL REFERENCES earned_equity_offer_revisions(id),
  scenario_set JSONB NOT NULL,
  result JSONB NOT NULL,
  calculator_version TEXT NOT NULL,
  schema_version INTEGER NOT NULL,
  input_hash TEXT NOT NULL CHECK (input_hash ~ '^[0-9a-f]{64}$'),
  company_assessment_ref TEXT,
  benchmark JSONB,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE (offer_revision_id, input_hash)
);

CREATE TABLE IF NOT EXISTS earned_equity_decisions (
  seq BIGINT GENERATED BY DEFAULT AS IDENTITY,
  id TEXT PRIMARY KEY,
  group_id TEXT NOT NULL REFERENCES earned_equity_decision_groups(id),
  payload JSONB NOT NULL,
  decided_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_earned_equity_decisions_group
  ON earned_equity_decisions(group_id, seq);

CREATE OR REPLACE FUNCTION radar_earned_equity_append_only() RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
  -- Restore and deliberate purge set this transaction-local flag; nothing else may rewrite history.
  IF current_setting('radar.earned_equity_maintenance', true) = 'on' THEN
    IF TG_OP = 'DELETE' THEN RETURN OLD; END IF;
    RETURN NEW;
  END IF;
  RAISE EXCEPTION '% is append-only', TG_TABLE_NAME;
END;
$$;

DROP TRIGGER IF EXISTS radar_earned_equity_offer_revisions_append_only ON earned_equity_offer_revisions;
CREATE TRIGGER radar_earned_equity_offer_revisions_append_only
  BEFORE UPDATE OR DELETE ON earned_equity_offer_revisions
  FOR EACH ROW EXECUTE FUNCTION radar_earned_equity_append_only();

DROP TRIGGER IF EXISTS radar_earned_equity_analysis_snapshots_append_only ON earned_equity_analysis_snapshots;
CREATE TRIGGER radar_earned_equity_analysis_snapshots_append_only
  BEFORE UPDATE OR DELETE ON earned_equity_analysis_snapshots
  FOR EACH ROW EXECUTE FUNCTION radar_earned_equity_append_only();

DROP TRIGGER IF EXISTS radar_earned_equity_decisions_append_only ON earned_equity_decisions;
CREATE TRIGGER radar_earned_equity_decisions_append_only
  BEFORE UPDATE OR DELETE ON earned_equity_decisions
  FOR EACH ROW EXECUTE FUNCTION radar_earned_equity_append_only();
